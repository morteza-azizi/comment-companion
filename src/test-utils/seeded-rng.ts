// Small deterministic PRNG (mulberry32) used only in tests so randomness in
// the generator can be exercised reproducibly instead of relying on
// Math.random, per the "use injectable RNG so tests are reliable" goal.
export function seededRng(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
